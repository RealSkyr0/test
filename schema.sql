CREATE TABLE IF NOT EXISTS users(
  id INTEGER PRIMARY KEY AUTOINCREMENT, sub TEXT UNIQUE NOT NULL, name TEXT,
  balance INTEGER NOT NULL DEFAULT 1000 CHECK(balance >= 0));
CREATE TABLE IF NOT EXISTS sessions(hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS rounds(
  id INTEGER PRIMARY KEY, seed TEXT NOT NULL, seed_hash TEXT NOT NULL, crash INTEGER NOT NULL,
  run_start INTEGER NOT NULL, crash_ms INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS bets(
  user_id INTEGER NOT NULL, round_id INTEGER NOT NULL, amount INTEGER NOT NULL, auto INTEGER,
  cashout INTEGER, payout INTEGER NOT NULL DEFAULT 0,
  charged INTEGER NOT NULL DEFAULT 0, credited INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY(user_id, round_id));
